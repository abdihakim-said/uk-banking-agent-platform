"""Generate the SLO recording rules and multi-window, multi-burn-rate alerts (Google SRE workbook, chapter 5).

    python scripts/gen_slo_rules.py

Writes deploy/helm/uk-banking-agent-platform/files/rules/{slo,alerts}.yaml. The Helm chart ships them as a
PrometheusRule and docker compose mounts the same files, so there is one definition. See docs/slo.md.
"""

from __future__ import annotations

from pathlib import Path

import yaml

OUT = Path("deploy/helm/uk-banking-agent-platform/files/rules")
WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d", "30d"]

AVAIL_ERR = ('(sum(rate(gateway_requests_total{{outcome=~"agent_unavailable|agent_error"}}[{w}])) or vector(0))\n'
             '+ (sum(rate(agent_turns_total{{outcome="unavailable"}}[{w}])) or vector(0))')
AVAIL_TOTAL = 'sum(rate(gateway_requests_total{{outcome=~"ok|agent_unavailable|agent_error"}}[{w}]))'
# prometheus_client renders bucket bounds as floats, so the 15s bucket is le="15.0", not le="15".
LAT_GOOD = 'sum(rate(gateway_request_duration_seconds_bucket{{le="15.0"}}[{w}]))'
LAT_TOTAL = 'sum(rate(gateway_request_duration_seconds_count[{w}]))'

SLOS = {
    "availability": ("availability_error_ratio", 0.005,
                     "99.5% of chat turns get a real answer (not an error or 'assistant unavailable')"),
    "latency": ("latency_slow_ratio", 0.05, "95% of successful chat turns complete within 15 seconds"),
}
BURN = [("page", "1h", "5m", 14.4, "2% of the 30-day budget in 1 hour"),
        ("page", "6h", "30m", 6, "5% of the 30-day budget in 6 hours"),
        ("ticket", "1d", "2h", 3, "10% of the 30-day budget in 1 day"),
        ("ticket", "3d", "6h", 1, "10% of the 30-day budget in 3 days")]


def slo_rules() -> dict:
    rec = []
    for w in WINDOWS:
        rec.append({"record": f"slo:availability_error_ratio:rate{w}",
                    "expr": f"({AVAIL_ERR.format(w=w)})\n/ clamp_min({AVAIL_TOTAL.format(w=w)}, 1e-9)"})
        rec.append({"record": f"slo:latency_slow_ratio:rate{w}",
                    "expr": f"1 - ({LAT_GOOD.format(w=w)}\n/ clamp_min({LAT_TOTAL.format(w=w)}, 1e-9))"})
    alerts = []
    for name, (metric, budget, desc) in SLOS.items():
        for sev, long_w, short_w, factor, period in BURN:
            alerts.append({
                "alert": f"SLO{name.capitalize()}BurnRate{long_w}",
                "expr": (f"slo:{metric}:rate{long_w} > ({factor} * {budget})\n"
                         f"and slo:{metric}:rate{short_w} > ({factor} * {budget})"),
                "labels": {"severity": sev, "slo": name},
                "annotations": {"summary": f"{name.capitalize()} SLO burning fast: {period}",
                                "description": f"SLO: {desc}. Burn rate over {long_w} and {short_w} is above {factor}x."},
            })
    return {"groups": [{"name": "bank-assistant-slo-recording", "interval": "30s", "rules": rec},
                       {"name": "bank-assistant-slo-alerts", "rules": alerts}]}


def operational_rules() -> dict:
    return {"groups": [{"name": "bank-assistant-operational", "rules": [
        {"alert": "ServiceDown", "expr": 'up{job=~".*(gateway|agent|mcp).*"} == 0', "for": "2m",
         "labels": {"severity": "page"},
         "annotations": {"summary": "{{ $labels.job }} {{ $labels.instance }} is down or unreachable"}},
        {"alert": "LLMFallbackActive", "expr": "sum(rate(llm_fallbacks_total[5m])) > 0", "for": "5m",
         "labels": {"severity": "ticket"}, "annotations": {"summary": "Turns are being served by a fallback LLM provider"}},
        {"alert": "GuardrailReplacingReplies", "expr": 'sum(rate(guardrail_events_total{guard="groundedness"}[15m])) > 0.05',
         "for": "15m", "labels": {"severity": "ticket"},
         "annotations": {"summary": "The output guard is replacing ungrounded replies; check the model and prompts"}},
        {"alert": "LLMSpendHigh", "expr": "sum(increase(llm_cost_usd_total[1h])) > 20", "labels": {"severity": "ticket"},
         "annotations": {"summary": "LLM spend above $20 in the last hour"}},
        {"alert": "ToolErrorsHigh",
         "expr": ('sum(rate(mcp_tool_calls_total{outcome="error"}[5m]))\n'
                  '/ clamp_min(sum(rate(mcp_tool_calls_total[5m])), 1e-9) > 0.2'),
         "for": "10m", "labels": {"severity": "page"},
         "annotations": {"summary": "More than 20% of MCP tool calls are failing"}},
    ]}]}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    header = "# Generated by scripts/gen_slo_rules.py - edit that, not this file.\n"
    (OUT / "slo.yaml").write_text(header + yaml.safe_dump(slo_rules(), sort_keys=False, width=120))
    (OUT / "alerts.yaml").write_text(header + yaml.safe_dump(operational_rules(), sort_keys=False, width=120))
    print(f"wrote {OUT}/slo.yaml and {OUT}/alerts.yaml")


if __name__ == "__main__":
    main()
