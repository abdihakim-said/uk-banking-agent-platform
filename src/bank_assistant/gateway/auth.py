"""OAuth2 / OIDC bearer-token validation.

Production: tokens are validated against the identity provider's JWKS (``BANK_OIDC_JWKS_URL``), with issuer,
audience, expiry and scope checks. The customer id comes from a ``customer_id`` claim, which the IdP maps from
its user record, never from the request body.

Local development uses a key pair generated by ``scripts/dev_idp.py``.
"""

from __future__ import annotations

import ssl
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import jwt
from jwt import PyJWKClient

_ALGORITHMS = ["RS256", "ES256", "PS256"]
SCA_ACR = "urn:bank:sca:otp"
STEP_UP_MAX_AGE_SECONDS = 300


class AuthError(Exception):
    def __init__(self, status: int, detail: str) -> None:
        super().__init__(detail)
        self.status = status
        self.detail = detail


@dataclass(frozen=True)
class Principal:
    subject: str
    customer_id: str
    names: list[str]
    scopes: frozenset[str]


class JwtVerifier:
    def __init__(self, issuer: str, audience: str, required_scope: str, jwks_url: str | None = None,
                 public_key_pem: str | None = None, leeway_seconds: int = 30,
                 ssl_context: ssl.SSLContext | None = None) -> None:
        if not jwks_url and not public_key_pem:
            raise ValueError("either a JWKS URL or a public key is required")
        self.issuer = issuer
        self.audience = audience
        self.required_scope = required_scope
        self.leeway = leeway_seconds
        self._jwks = (PyJWKClient(jwks_url, cache_keys=True, lifespan=300, ssl_context=ssl_context)
                      if jwks_url else None)
        self._public_key = public_key_pem

    @classmethod
    def from_settings(cls, issuer: str, audience: str, scope: str, jwks_url: str | None,
                      dev_key_path: str | None, ssl_context: ssl.SSLContext | None = None) -> JwtVerifier:
        pem = Path(dev_key_path).read_text() if (jwks_url is None and dev_key_path) else None
        return cls(issuer, audience, scope, jwks_url, pem, ssl_context=ssl_context)

    def verify(self, authorization: str | None) -> Principal:
        if not authorization or not authorization.lower().startswith("bearer "):
            raise AuthError(401, "missing bearer token")
        token = authorization.split(" ", 1)[1].strip()
        try:
            key: Any = self._jwks.get_signing_key_from_jwt(token).key if self._jwks else self._public_key
            claims = jwt.decode(token, key, algorithms=_ALGORITHMS, audience=self.audience, issuer=self.issuer,
                                leeway=self.leeway, options={"require": ["exp", "iat", "sub", "iss", "aud"]})
        except jwt.ExpiredSignatureError as exc:
            raise AuthError(401, "token expired") from exc
        except (jwt.PyJWTError, ValueError) as exc:
            raise AuthError(401, "invalid token") from exc
        scopes = frozenset(str(claims.get("scope", "")).split())
        if self.required_scope not in scopes:
            raise AuthError(403, "missing scope")
        customer_id = claims.get("customer_id")
        if not isinstance(customer_id, str) or not customer_id:
            raise AuthError(403, "token is not linked to a customer")
        names = [str(claims[k]) for k in ("given_name", "family_name", "name") if claims.get(k)]
        return Principal(subject=str(claims["sub"]), customer_id=customer_id, names=names, scopes=scopes)

    def verify_step_up(self, token: str, principal: Principal) -> dict[str, str]:
        """Validate a step-up (strong customer authentication) token for this customer. Returns the action binding
        (``txn``) it approves. Same signature, issuer and audience checks as the access token, plus: it must be an SCA
        token (``acr``), for the same person, and fresh."""
        try:
            key: Any = self._jwks.get_signing_key_from_jwt(token).key if self._jwks else self._public_key
            claims = jwt.decode(token, key, algorithms=_ALGORITHMS, audience=self.audience, issuer=self.issuer,
                                leeway=self.leeway, options={"require": ["exp", "iat", "sub", "acr", "txn"]})
        except jwt.ExpiredSignatureError as exc:
            raise AuthError(401, "step-up token expired") from exc
        except (jwt.PyJWTError, ValueError) as exc:
            raise AuthError(401, "invalid step-up token") from exc
        if claims["acr"] != SCA_ACR:
            raise AuthError(403, "step-up token is not strong customer authentication")
        if claims["sub"] != principal.subject or claims.get("customer_id") != principal.customer_id:
            raise AuthError(403, "step-up token belongs to a different customer")
        if time.time() - float(claims["iat"]) > STEP_UP_MAX_AGE_SECONDS + self.leeway:
            raise AuthError(401, "step-up token is too old")
        return {"txn": str(claims["txn"]), "acr": str(claims["acr"])}
